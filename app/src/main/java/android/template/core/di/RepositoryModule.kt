package android.template.core.di

import android.template.data.DefaultTaskRepository
import android.template.domain.repository.TaskRepository
import dagger.Binds
import dagger.Module
import dagger.hilt.InstallIn
import dagger.hilt.components.SingletonComponent
import javax.inject.Singleton

@Module
@InstallIn(SingletonComponent::class)
interface RepositoryModule {
    @Binds
    @Singleton
    fun bindTaskRepository(impl: DefaultTaskRepository): TaskRepository
}